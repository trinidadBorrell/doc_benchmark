def run_aggregate(args):
    """Collect per-budget results, write global summaries and plots.

    Data sources (tried in order per emb/clf pair):

    1. **Chunk dirs** (new format):
       ``output_dir/budget_{N}/chunk_{R}/{emb}/{clf}/fold_metrics.csv``
       Written by chunked HTCondor jobs.  All chunks are concatenated and
       re-summarised here so the final summary reflects all repeats.

    2. **Legacy per-budget dirs** (old single-chunk format):
       ``output_dir/budget_{N}/{emb}/{clf}/summary_metrics.json``
       Written by the old budget-level jobs.  Used as-is when no chunk dirs exist.

    3. **Legacy global files** (single-repeat format):
       ``output_dir/{emb}/{clf}/summary_metrics.json``
       Written by the very old end-to-end run; a JSON array with one dict per budget.
    """
    output_dir = args.output_dir
    classifiers = ["svm", "mlp", "kernel_ridge", "random_forest"]

    budget_dirs = sorted(
        d
        for d in os.listdir(output_dir)
        if d.startswith("budget_") and op.isdir(op.join(output_dir, d))
    )

    # Discover embedding names from chunk_* subdirs inside budget dirs.
    emb_from_chunks = set()
    for bd in budget_dirs:
        bd_path = op.join(output_dir, bd)
        for entry in os.listdir(bd_path):
            if not entry.startswith("chunk_"):
                continue
            chunk_path = op.join(bd_path, entry)
            if not op.isdir(chunk_path):
                continue
            for sub in os.listdir(chunk_path):
                if op.isdir(op.join(chunk_path, sub)):
                    emb_from_chunks.add(sub)

    # Embedding names from legacy budget dirs (exclude repeat_* and chunk_*).
    emb_from_budget = set()
    for bd in budget_dirs:
        bd_path = op.join(output_dir, bd)
        for entry in os.listdir(bd_path):
            if op.isdir(op.join(bd_path, entry)) and not entry.startswith(("repeat_", "chunk_")):
                emb_from_budget.add(entry)

    # Legacy global dirs.
    emb_from_global = set()
    for entry in os.listdir(output_dir):
        entry_path = op.join(output_dir, entry)
        if not op.isdir(entry_path) or entry.startswith("budget_"):
            continue
        for clf in classifiers:
            if op.isfile(op.join(entry_path, clf, "summary_metrics.json")):
                emb_from_global.add(entry)
                break

    embedding_names = emb_from_chunks | emb_from_budget | emb_from_global
    if not embedding_names:
        print("No results found — nothing to aggregate.", flush=True)
        return

    all_results = {}

    for emb in sorted(embedding_names):
        all_results[emb] = {}
        for clf in classifiers:
            # ----------------------------------------------------------------
            # Source 1: chunk dirs — collect fold_metrics, re-summarise per budget.
            # ----------------------------------------------------------------
            if emb in emb_from_chunks:
                budget_fold_rows = {}  # budget → list[dict]
                for bd in budget_dirs:
                    budget_val = int(bd.replace("budget_", ""))
                    bd_path = op.join(output_dir, bd)
                    chunk_dirs = sorted(
                        e for e in os.listdir(bd_path)
                        if e.startswith("chunk_") and op.isdir(op.join(bd_path, e))
                    )
                    rows_for_budget = []
                    for chunk in chunk_dirs:
                        fold_csv = op.join(bd_path, chunk, emb, clf, "fold_metrics.csv")
                        if op.isfile(fold_csv):
                            rows_for_budget.extend(
                                pd.read_csv(fold_csv).to_dict(orient="records")
                            )
                    if rows_for_budget:
                        budget_fold_rows[budget_val] = rows_for_budget

                if not budget_fold_rows:
                    continue

                summary_rows = []
                for budget_val in sorted(budget_fold_rows):
                    rows = budget_fold_rows[budget_val]
                    n_repeats_found = len({r["repeat"] for r in rows})
                    summary = summarize_fold_rows(
                        rows=rows,
                        n_sessions_requested=budget_val,
                        n_repeats=n_repeats_found,
                    )
                    summary["embedding_type"] = emb
                    summary["classifier"] = clf
                    summary_rows.append(summary)

                clf_dir = op.join(output_dir, emb, clf)
                ensure_dir(clf_dir)
                pd.DataFrame(summary_rows).to_csv(
                    op.join(clf_dir, "summary_metrics.csv"), index=False
                )
                with open(op.join(clf_dir, "summary_metrics.json"), "w") as fh:
                    json.dump(summary_rows, fh, indent=2)
                total_folds = sum(len(budget_fold_rows[b]) for b in budget_fold_rows)
                print(
                    f"  [{emb}] [{clf}] aggregated {len(summary_rows)} budgets "
                    f"from chunk dirs ({total_folds} fold rows total)",
                    flush=True,
                )
                all_results[emb][clf] = summary_rows
                continue

            # ----------------------------------------------------------------
            # Source 2: legacy per-budget summary_metrics.json.
            # ----------------------------------------------------------------
            summary_rows = []
            if emb in emb_from_budget:
                for bd in budget_dirs:
                    summary_path = op.join(output_dir, bd, emb, clf, "summary_metrics.json")
                    if not op.isfile(summary_path):
                        continue
                    with open(summary_path) as fh:
                        summary = json.load(fh)
                    if isinstance(summary, list):
                        summary_rows.extend(summary)
                    else:
                        summary_rows.append(summary)

            # ----------------------------------------------------------------
            # Source 3: legacy global file.
            # ----------------------------------------------------------------
            if not summary_rows and emb in emb_from_global:
                legacy_path = op.join(output_dir, emb, clf, "summary_metrics.json")
                if op.isfile(legacy_path):
                    with open(legacy_path) as fh:
                        legacy = json.load(fh)
                    summary_rows = legacy if isinstance(legacy, list) else [legacy]
                    if summary_rows:
                        print(
                            f"  [{emb}] [{clf}] using legacy single-repeat data "
                            f"({len(summary_rows)} budget points)",
                            flush=True,
                        )

            if not summary_rows:
                continue

            summary_rows = sorted(summary_rows, key=lambda r: r["n_sessions_requested"])

            if emb in emb_from_budget:
                clf_dir = op.join(output_dir, emb, clf)
                ensure_dir(clf_dir)
                pd.DataFrame(summary_rows).to_csv(
                    op.join(clf_dir, "summary_metrics.csv"), index=False
                )
                with open(op.join(clf_dir, "summary_metrics.json"), "w") as fh:
                    json.dump(summary_rows, fh, indent=2)
                print(
                    f"  [{emb}] [{clf}] aggregated {len(summary_rows)} budget points",
                    flush=True,
                )

            all_results[emb][clf] = summary_rows

    plot_auc_curves(all_results, output_dir)
    plot_auc_overview(all_results, output_dir)

    with open(op.join(output_dir, "learning_curve_overview.json"), "w") as fh:
        json.dump(all_results, fh, indent=2)

    print("Aggregation complete.", flush=True)


