"""Learning curve benchmark for CRS prediction from embeddings.

This script runs a CRS-only nested cross-validation benchmark across multiple
embedding sources and classifiers. For each embedding type, it evaluates four
classifiers (SVM, MLP, Kernel Ridge, Random Forest) on progressively larger
subsets defined by a target number of sessions.

Repeated cross-validation
--------------------------
Each budget point is evaluated with ``--n-repeats`` independent repetitions.
Every repeat independently re-samples a different balanced session subset from
the common pool (sampling seed = ``random_state + budget * 1000 + repeat``) and
re-generates fresh nested CV folds (fold seed = ``random_state + repeat``).
Metrics are aggregated across all ``n_folds × n_repeats`` evaluations.

Why 100 repeats is not redundant
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
For small budgets (20–40 sessions) drawn from a pool of ~150+ sessions, the
number of possible class-balanced subsets is astronomically large (e.g.
C(75, 10) × C(75, 10) ≈ 10^14), so collisions between repeats are negligible.
At large budgets near the pool size, subsets overlap more but the fold
assignments still differ per repeat (different ``random_state + r`` seed),
ensuring variance estimates reflect true split variability.

Three-phase workflow
---------------------
The script supports three operating modes controlled by CLI flags:

  1. Setup (``--setup-only``):
       Builds the common session pool, generates all (budget × repeat) splits,
       writes them to disk, and emits ``budget_list.txt`` for HTCondor.

  2. Run (``--budget N``):
       Loads pre-computed splits for budget N and evaluates all embedding types
       × classifiers × repeats.  Intended for per-budget HTCondor jobs.

  3. Aggregate (``--aggregate-only``):
       Reads all per-budget result files, merges across budgets and repeats,
       writes global summary files and produces plots.

  Full end-to-end run (no special flags):
       Runs all three phases sequentially (setup → all budgets → aggregate).
       Useful for small experiments or local testing.

Key design principle
--------------------
All embedding types (foundation models + domain-knowledge baseline) are
evaluated on the **exact same** session subsets and **identical** nested CV
fold assignments at every budget × repeat point.

Directory layout
----------------
::

    LEARNING_CURVE/
    ├── budget_list.txt                            ← generated by setup
    ├── budget_{N}/
    │   ├── repeat_{R}/common_cv_splits.json       ← one per repeat
    │   └── {embedding_type}/{classifier}/
    │       ├── fold_metrics.csv                   ← all folds × repeats
    │       └── summary_metrics.{csv,json}         ← aggregated over folds×repeats
    ├── {embedding_type}/{classifier}/
    │   ├── summary_metrics.{csv,json}             ← one row per budget (aggregate)
    └── auc_learning_curve_{classifier}.png
"""

