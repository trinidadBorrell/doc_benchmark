def generate_budget_splits(
    common_sessions,
    labels,
    session_budgets,
    n_repeats,
    n_outer_folds,
    random_state,
    output_dir,
    verbose=True,
):
    """Generate and save (budget × repeat) splits.  Return budget_splits dict.

    Parameters
    ----------
    common_sessions:
        Sorted list of all available session keys.
    labels:
        Full labels dict (session_key → int).
    session_budgets:
        Sorted list of budget sizes to evaluate.
    n_repeats:
        Number of independent repetitions per budget.
    n_outer_folds:
        Desired number of outer CV folds.
    random_state:
        Base seed.  Sampling seed = random_state + budget * 1000 + repeat.
        Fold seed = random_state + repeat.
    output_dir:
        Root output directory where splits are persisted.
    verbose:
        Print progress.

    Returns
    -------
    budget_splits : dict[int, list[dict]]
        Maps budget → list of repeat dicts, each containing:
        ``{sessions, folds, n_subjects, n_sessions, repeat}``.
    valid_budgets : list[int]
        Budgets that were successfully processed.
    """
    budget_splits = {}
    valid_budgets = []

    for budget in session_budgets:
        if budget > len(common_sessions):
            if verbose:
                print(
                    f"  budget={budget}: skipped (common pool has only "
                    f"{len(common_sessions)} sessions)",
                    flush=True,
                )
            continue

        repeats_data = []
        for r in range(n_repeats):
            sample_seed = random_state + budget * 1000 + r
            fold_seed = random_state + r

            budget_sessions = sample_sessions_balanced(
                session_keys=common_sessions,
                labels=labels,
                n_sessions=budget,
                random_state=sample_seed,
            )

            budget_folds = generate_nested_cv_folds(
                common_sessions=budget_sessions,
                labels=labels,
                n_outer=n_outer_folds,
                random_state=fold_seed,
            )

            n_subjects = len({k.split("_ses-")[0] for k in budget_sessions})
            repeats_data.append(
                {
                    "sessions": budget_sessions,
                    "folds": budget_folds,
                    "n_subjects": n_subjects,
                    "n_sessions": len(budget_sessions),
                    "repeat": r,
                }
            )

            splits_dir = op.join(output_dir, f"budget_{budget}", f"repeat_{r}")
            ensure_dir(splits_dir)
            save_cv_splits(
                folds=budget_folds,
                common_sessions=budget_sessions,
                labels=labels,
                path=op.join(splits_dir, "common_cv_splits.json"),
            )

        budget_splits[budget] = repeats_data
        valid_budgets.append(budget)

        if verbose:
            n_subj_vals = [rd["n_subjects"] for rd in repeats_data]
            print(
                f"  budget={budget}: {n_repeats} repeats, "
                f"subjects/repeat={np.mean(n_subj_vals):.1f}±{np.std(n_subj_vals):.1f}, "
                f"{len(repeats_data[0]['folds'])} outer folds",
                flush=True,
            )

    return budget_splits, valid_budgets


def load_splits_for_budget(budget, output_dir, n_repeats, repeat_start=0):
    """Load pre-computed repeat splits for one budget from disk.

    Parameters
    ----------
    budget:
        Budget size (session count).
    output_dir:
        Root output directory (LEARNING_CURVE/).
    n_repeats:
        Number of repeats to load (chunk size).
    repeat_start:
        Index of the first repeat to load (for chunked HTCondor jobs).
        Repeats ``[repeat_start, repeat_start + n_repeats)`` are loaded.

    Returns
    -------
    list[dict] — one dict per repeat: ``{sessions, folds, n_subjects, n_sessions, repeat}``.
    """
    repeats_data = []
    for r in range(repeat_start, repeat_start + n_repeats):
        path = op.join(output_dir, f"budget_{budget}", f"repeat_{r}", "common_cv_splits.json")
        if not op.isfile(path):
            raise FileNotFoundError(
                f"Pre-computed splits not found: {path}\n"
                "Run with --setup-only first to generate all splits."
            )
        folds, sessions, lbl = load_cv_splits(path)
        n_subjects = len({k.split("_ses-")[0] for k in sessions})
        repeats_data.append(
            {
                "sessions": sessions,
                "folds": folds,
                "n_subjects": n_subjects,
                "n_sessions": len(sessions),
                "repeat": r,
            }
        )
    return repeats_data


