def plot_auc_curves(all_results, output_dir):
    """Plot AUC learning curves by classifier with one curve per embedding type."""
    classifiers = ["svm", "mlp", "kernel_ridge", "random_forest"]

    plt.rcParams["font.family"] = "serif"
    plt.rcParams["figure.dpi"] = 120

    for classifier_name in classifiers:
        fig, ax = plt.subplots(figsize=(9, 6))
        all_xticks = set()

        for embedding_name in sorted(all_results):
            summary_rows = all_results[embedding_name].get(classifier_name, [])
            if not summary_rows:
                continue

            summary_rows = sorted(
                summary_rows, key=lambda r: r["n_sessions_requested"]
            )
            x = [r["n_sessions_requested"] for r in summary_rows]
            y = [r["auc_mean"] for r in summary_rows]
            yerr = [
                r["auc_std"] if r.get("auc_std") is not None else 0.0
                for r in summary_rows
            ]

            valid = [
                (xi, yi, ei)
                for xi, yi, ei in zip(x, y, yerr)
                if yi is not None and not (isinstance(yi, float) and np.isnan(yi))
            ]
            if not valid:
                continue
            x_valid = [v[0] for v in valid]
            y_valid = [v[1] for v in valid]
            e_valid = [v[2] for v in valid]
            all_xticks.update(x_valid)

            n_repeats = summary_rows[0].get("n_repeats", 1)
            label = f"{embedding_name} (×{n_repeats} repeats)" if n_repeats > 1 else embedding_name

            ax.plot(x_valid, y_valid, marker="o", linewidth=2, label=label)
            ax.fill_between(
                x_valid,
                np.array(y_valid) - np.array(e_valid),
                np.array(y_valid) + np.array(e_valid),
                alpha=0.15,
            )

        ax.set_title(f"AUC Learning Curve - {classifier_name}")
        ax.set_xlabel("Number of Sessions (budget)")
        ax.set_ylabel("AUC (mean ± std across folds × repeats)")
        if all_xticks:
            ticks = sorted(all_xticks)
            # Show at most 20 tick labels to avoid crowding.
            if len(ticks) > 20:
                step = max(1, len(ticks) // 20)
                ticks = ticks[::step]
            ax.set_xticks(ticks)
        ax.set_ylim(0.0, 1.0)
        ax.grid(True, alpha=0.3)
        ax.legend(loc="best")

        fig.tight_layout()
        out_file = op.join(output_dir, f"auc_learning_curve_{classifier_name}.png")
        fig.savefig(out_file, dpi=180, bbox_inches="tight")
        plt.close(fig)


def _extract_valid_xy(summary_rows):
    """Return (x_valid, y_valid, e_valid) filtering out None/NaN AUC entries."""
    summary_rows = sorted(summary_rows, key=lambda r: r["n_sessions_requested"])
    x = [r["n_sessions_requested"] for r in summary_rows]
    y = [r["auc_mean"] for r in summary_rows]
    yerr = [r["auc_std"] if r.get("auc_std") is not None else 0.0 for r in summary_rows]
    valid = [
        (xi, yi, ei)
        for xi, yi, ei in zip(x, y, yerr)
        if yi is not None and not (isinstance(yi, float) and np.isnan(yi))
    ]
    if not valid:
        return [], [], []
    return [v[0] for v in valid], [v[1] for v in valid], [v[2] for v in valid]


def _draw_panel(ax, x_valid, y_valid, e_valid):
    """Draw AUC curve + shading + dashed linear fit with slope in legend."""
    ax.plot(x_valid, y_valid, marker="o", linewidth=2, color="#1f77b4", label="AUC")
    ax.fill_between(
        x_valid,
        np.array(y_valid) - np.array(e_valid),
        np.array(y_valid) + np.array(e_valid),
        alpha=0.15,
        color="#1f77b4",
    )
    if len(x_valid) >= 2:
        slope, intercept = np.polyfit(x_valid, y_valid, 1)
        x_fit = np.linspace(x_valid[0], x_valid[-1], 100)
        ax.plot(
            x_fit,
            slope * x_fit + intercept,
            linestyle="--",
            linewidth=1.5,
            color="orange",
            label=f"Linear fit (slope={slope:.4f})",
        )


def plot_auc_overview(all_results, output_dir):
    """4-row × N-column overview: rows = classifiers, columns = FM models.

    Mirrors the layout of ``auc_learning_curve_plots.py`` so that
    ``--aggregate-only`` produces the same overview figure.
    """
    classifiers = ["svm", "mlp", "kernel_ridge", "random_forest"]
    # Preserve a stable column order: known models first, then any extras.
    known_order = ["TOTEM", "CBraMod", "LaBram", "NeuroLM", "Domain_Knowledge"]
    fm_models = [m for m in known_order if m in all_results] + [
        m for m in sorted(all_results) if m not in known_order
    ]
    if not fm_models:
        return

    plt.rcParams["font.family"] = "serif"
    plt.rcParams["figure.dpi"] = 120

    n_rows = len(classifiers)
    n_cols = len(fm_models)
    fig, axes = plt.subplots(
        n_rows,
        n_cols,
        figsize=(4.5 * n_cols, 4 * n_rows),
        sharey="row",
        sharex="col",
    )
    # Normalise axes to 2-D array even when n_rows or n_cols == 1.
    axes = np.array(axes).reshape(n_rows, n_cols)

    for row_idx, classifier_name in enumerate(classifiers):
        for col_idx, embedding_name in enumerate(fm_models):
            ax = axes[row_idx][col_idx]

            if row_idx == 0:
                ax.set_title(embedding_name, fontsize=11, fontweight="bold")
            if col_idx == 0:
                ax.set_ylabel(f"{classifier_name}\nAUC", fontsize=9)

            ax.set_xlabel("Subjects", fontsize=8)
            ax.set_ylim(0.0, 1.0)
            ax.grid(True, alpha=0.3)

            summary_rows = all_results.get(embedding_name, {}).get(classifier_name, [])
            if not summary_rows:
                continue

            x_valid, y_valid, e_valid = _extract_valid_xy(summary_rows)
            if not x_valid:
                continue

            _draw_panel(ax, x_valid, y_valid, e_valid)

            ax.set_xticks(x_valid)
            ax.tick_params(axis="x", rotation=45, labelsize=7)
            ax.legend(fontsize=6.5, loc="lower right")

    fig.suptitle("AUC Learning Curves — All classifiers & FM models", fontsize=13)
    fig.tight_layout()
    out_file = op.join(output_dir, "auc_learning_curve_overview.png")
    fig.savefig(out_file, dpi=180, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved {out_file}", flush=True)


