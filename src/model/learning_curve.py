def main():
    args = parse_args()
    ensure_dir(args.output_dir)

    # ------------------------------------------------------------------
    # Aggregate-only mode: collect per-budget results and plot.
    # ------------------------------------------------------------------
    if args.aggregate_only:
        print("=" * 80, flush=True)
        print("LEARNING CURVE — AGGREGATE MODE", flush=True)
        print("=" * 80, flush=True)
        print(f"Output dir: {args.output_dir}", flush=True)
        run_aggregate(args)
        return

    print("=" * 80, flush=True)
    print("LEARNING CURVE BENCHMARK (CRS only)", flush=True)
    print("=" * 80, flush=True)
    print(f"Results root: {args.results_root}", flush=True)
    print(f"Output dir:   {args.output_dir}", flush=True)
    print(f"Repeats/budget: {args.n_repeats}", flush=True)

    labels = load_crs_labels(args.labels_file)
    print(f"Loaded CRS labels: {len(labels)} sessions", flush=True)

    embedding_source_specs = build_embedding_source_specs(
        results_root=args.results_root,
        marker_csv=args.marker_csv,
        reduction_letter=args.marker_reduction,
    )
    if not embedding_source_specs:
        raise ValueError("No embedding sources available")

    source_names = sorted(embedding_source_specs.keys())
    print(f"Embedding types: {source_names}", flush=True)

    # ------------------------------------------------------------------
    # Setup phase — build common pool and generate (budget × repeat) splits.
    # Skipped in --budget mode (splits are loaded from disk instead).
    # ------------------------------------------------------------------
    if args.budget is None:
        print("\nBuilding common session pool ...", flush=True)
        source_loaders = {
            name: (lambda spec=spec: load_embeddings_from_spec(spec))
            for name, spec in embedding_source_specs.items()
        }
        common_sessions = build_common_session_pool(
            source_loaders, labels, verbose=True
        )
        n_common_subjects = len({k.split("_ses-")[0] for k in common_sessions})
        print(
            f"Common pool: {len(common_sessions)} sessions, "
            f"{n_common_subjects} subjects\n",
            flush=True,
        )

        session_budgets = sorted(set(args.session_budgets))
        print(
            f"Pre-computing {len(session_budgets)} budget × {args.n_repeats} repeat "
            "splits ...",
            flush=True,
        )
        budget_splits, valid_budgets = generate_budget_splits(
            common_sessions=common_sessions,
            labels=labels,
            session_budgets=session_budgets,
            n_repeats=args.n_repeats,
            n_outer_folds=args.n_outer_folds,
            random_state=args.random_state,
            output_dir=args.output_dir,
            verbose=True,
        )

        if not budget_splits:
            raise ValueError(
                f"No valid budgets after filtering against the common pool size "
                f"({len(common_sessions)} sessions)."
            )

        # Write budget_list.txt for HTCondor parametric submission.
        # Format: budget <TAB> repeat_start <TAB> chunk_size
        # One line per (budget, repeat_chunk) pair so HTCondor queues a separate
        # job for each chunk.  chunk_size = min(repeat_chunk_size, n_repeats).
        chunk_size = min(args.repeat_chunk_size, args.n_repeats)
        budget_list_path = op.join(args.output_dir, "budget_list.txt")
        n_chunks = (args.n_repeats + chunk_size - 1) // chunk_size
        with open(budget_list_path, "w") as fh:
            for b in valid_budgets:
                for chunk_idx in range(n_chunks):
                    r_start = chunk_idx * chunk_size
                    r_size = min(chunk_size, args.n_repeats - r_start)
                    fh.write(f"{b}\t{r_start}\t{r_size}\n")
        n_entries = len(valid_budgets) * n_chunks
        print(
            f"\nBudget list ({n_entries} entries = {len(valid_budgets)} budgets × "
            f"{n_chunks} chunks of {chunk_size} repeats) saved to: {budget_list_path}",
            flush=True,
        )

        if args.setup_only:
            print("Setup complete (--setup-only). Exiting.", flush=True)
            return

    else:
        # Per-budget HTCondor mode: load pre-computed splits for this budget only.
        repeat_start = args.repeat_start
        print(
            f"\nPer-budget mode: loading pre-computed splits for budget={args.budget} "
            f"repeats [{repeat_start}, {repeat_start + args.n_repeats}) ...",
            flush=True,
        )
        repeats_data = load_splits_for_budget(
            budget=args.budget,
            output_dir=args.output_dir,
            n_repeats=args.n_repeats,
            repeat_start=repeat_start,
        )
        budget_splits = {args.budget: repeats_data}
        print(f"Loaded {len(repeats_data)} repeats.", flush=True)

    # ------------------------------------------------------------------
    # Run phase — evaluate each embedding type in parallel.
    # ------------------------------------------------------------------
    n_jobs = args.n_jobs if args.n_jobs is not None else len(source_names)
    n_jobs = max(1, min(n_jobs, len(source_names)))
    print(f"\nParallel embedding jobs: {n_jobs}", flush=True)

    repeat_start = getattr(args, "repeat_start", 0)

    job_outputs = Parallel(
        n_jobs=n_jobs,
        backend=args.parallel_backend,
        verbose=args.parallel_verbose,
    )(
        delayed(run_embedding_job)(
            embedding_name=name,
            source_spec=embedding_source_specs[name],
            labels=labels,
            budget_splits=budget_splits,
            output_dir=args.output_dir,
            random_state=args.random_state,
            repeat_start=repeat_start,
        )
        for name in source_names
    )

    # ------------------------------------------------------------------
    # Aggregate — only in full end-to-end mode (not per-budget HTCondor).
    # ------------------------------------------------------------------
    if args.budget is None:
        print("\nAggregating results ...", flush=True)
        run_aggregate(args)

    print("Finished.", flush=True)
    print(f"Outputs saved to: {args.output_dir}", flush=True)


if __name__ == "__main__":
    main()
